import { useEffect, useState } from "react";
import { marked } from "marked";
import { api } from "../api";

export default function DocsView({ versionId }: { versionId: number }) {
  const [markdown, setMarkdown] = useState<string>("");
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    setMarkdown("");
    setError(null);
    api.docs(versionId).then((d) => setMarkdown(d.content)).catch((e: Error) => setError(e.message));
  }, [versionId]);

  function download() {
    const blob = new Blob([markdown], { type: "text/markdown" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = "api-docs.md";
    a.click();
    URL.revokeObjectURL(url);
  }

  if (error) return <p className="error">{error}</p>;
  if (!markdown) return <p className="muted">Generating documentation…</p>;

  return (
    <div>
      <div className="row toolbar">
        <button className="secondary" onClick={download}>Download Markdown</button>
      </div>
      {/* Content is generated by our own backend from the stored spec. */}
      <article className="markdown" dangerouslySetInnerHTML={{ __html: marked.parse(markdown, { async: false }) }} />
    </div>
  );
}
